import path from "node:path"
import { existsSync, readFileSync } from "node:fs"
import { pathToFileURL } from "node:url"
import { BROWSER_PERMISSIONS, DEFAULT_CONFIG, isRecord } from "./schema"
import { checkJail } from "../policy/jail"

export type GenerateOptions = {
  workspace: string
  runtimePath?: string
  mcpCommand?: string[]
}

export type GenerateResult = {
  path: string
  changed: boolean
  config: Record<string, unknown>
}

export type EnsureResult = {
  path: string
  created: boolean
}

export const GUARD_ENTRY = "./.kilo/plugins/kilo-browser-guard.ts"
export const INSTRUCTIONS_ENTRY = ".kilo/kilo-browser/AGENTS.md"

export async function generateKiloConfig(options: GenerateOptions): Promise<GenerateResult> {
  const file = path.join(options.workspace, ".kilo", "kilo.json")
  await checkJail([options.workspace], file)
  const runtime = options.runtimePath ?? path.join(options.workspace, ".kilo", "kilo-browser", "runtime.json")
  const existingRaw = await readJson(file)
  const config = isRecord(existingRaw) ? existingRaw : {}
  const changed = { value: Object.keys(config).length === 0 }
  const before = JSON.stringify(config)

  if (config.$schema === undefined) config.$schema = "https://app.kilo.ai/config.json"

  if (config.permission === undefined) config.permission = {}
  if (!isRecord(config.permission)) throw new Error("cannot merge .kilo/kilo.json: permission must be an object")
  for (const [key, value] of Object.entries(BROWSER_PERMISSIONS)) {
    if (config.permission[key] === undefined) config.permission[key] = value
  }

  if (config.instructions === undefined) config.instructions = []
  if (!Array.isArray(config.instructions)) {
    throw new Error("cannot merge .kilo/kilo.json: instructions must be an array")
  }
  if (!config.instructions.includes(INSTRUCTIONS_ENTRY)) config.instructions.push(INSTRUCTIONS_ENTRY)

  if (config.plugin === undefined) config.plugin = []
  if (!Array.isArray(config.plugin)) throw new Error("cannot merge .kilo/kilo.json: plugin must be an array")
  if (!config.plugin.includes(GUARD_ENTRY)) config.plugin.push(GUARD_ENTRY)

  if (config.mcp === undefined) config.mcp = {}
  if (!isRecord(config.mcp)) throw new Error("cannot merge .kilo/kilo.json: mcp must be an object")
  if (config.mcp.browser === undefined) {
    config.mcp.browser = {
      type: "local",
      command: [...(options.mcpCommand ?? defaultMcpCommand()), "--runtime", runtime],
      environment: { KILO_BROWSER_RUNTIME: runtime },
      enabled: true,
      timeout: 60000,
    }
  } else {
    repointBrowserMcp(config.mcp.browser, runtime, options.mcpCommand)
  }

  const after = JSON.stringify(config)
  const dirty = changed.value || before !== after
  if (dirty) {
    await Bun.write(file, `${JSON.stringify(config, null, 2)}\n`)
  }
  return { path: file, changed: dirty, config }
}

export async function ensureBrowserConfig(workspace: string): Promise<EnsureResult> {
  const file = path.join(workspace, ".kilo", "kilo-browser.json")
  await checkJail([workspace], file)
  const exists = await Bun.file(file).exists()
  if (exists) return { path: file, created: false }
  await Bun.write(file, `${JSON.stringify({ $schema: "https://kilo.ai/schemas/kilo-browser.json", ...DEFAULT_CONFIG }, null, 2)}\n`)
  return { path: file, created: true }
}

export const GUARD_MARKER = "// Generated by kilo-browser. Do not edit; kilo-browser start rewrites this file."

export async function ensureGuard(workspace: string): Promise<EnsureResult> {
  const file = path.join(workspace, ".kilo", "plugins", "kilo-browser-guard.ts")
  await checkJail([workspace], file)
  const target = guardModule()
  if (!path.isAbsolute(target)) throw new Error(`guard module path must be absolute: ${target}`)
  if (!existsSync(target)) throw new Error(`guard module is missing: ${target}`)
  const source = [
    GUARD_MARKER,
    `export { default } from ${JSON.stringify(pathToFileURL(target).href)}`,
    "",
  ].join("\n")
  const exists = await Bun.file(file).exists()
  if (exists) {
    const current = await Bun.file(file).text()
    if (!current.startsWith(GUARD_MARKER)) return { path: file, created: false }
    if (current === source) return { path: file, created: false }
  }
  await Bun.write(file, source)
  return { path: file, created: !exists }
}

export function guardModule() {
  const root = packageRoot()
  // Prefer the built bundle: the bridge spawns the packaged `kilo` binary, which
  // can import external JavaScript but cannot transpile the TypeScript source at
  // runtime, so a `src/*.ts` guard would fail to load there.
  const dist = path.join(root, "dist", "plugin", "kilo-browser-guard.js")
  if (existsSync(dist)) return dist
  return path.join(root, "src", "plugin", "kilo-browser-guard.ts")
}

export function defaultMcpCommand(): string[] {
  const binary = Bun.which("kilo-browser-mcp")
  if (binary) return [binary]
  const root = packageRoot()
  const dist = path.join(root, "dist", "mcp", "main.js")
  if (existsSync(dist)) return [process.execPath, dist]
  const source = path.join(root, "src", "mcp", "main.ts")
  return [process.execPath, source]
}

/**
 * Re-point an existing `mcp.browser` entry at the current runtime file. The entry
 * is generated only once, so a bridge started from a different workspace (or a
 * copied `.kilo/kilo.json`) would otherwise keep a stale `--runtime` path and the
 * MCP shim would read a dead runtime and fail with ECONNREFUSED. Keep whatever
 * launcher is configured; only fix the path argument and the environment key.
 */
function repointBrowserMcp(entry: unknown, runtime: string, mcpCommand?: string[]) {
  if (!isRecord(entry)) return
  const command = Array.isArray(entry.command) ? entry.command : undefined
  if (command) {
    const index = command.indexOf("--runtime")
    if (index >= 0) command[index + 1] = runtime
    else command.push("--runtime", runtime)
  } else {
    entry.command = [...(mcpCommand ?? defaultMcpCommand()), "--runtime", runtime]
  }
  const environment = isRecord(entry.environment) ? entry.environment : {}
  environment.KILO_BROWSER_RUNTIME = runtime
  entry.environment = environment
}


function packageRoot() {
  let dir = import.meta.dir
  while (true) {
    const file = path.join(dir, "package.json")
    if (existsSync(file)) {
      try {
        const parsed = JSON.parse(readFileSync(file, "utf8")) as { name?: string }
        if (parsed.name === "@kilocode/kilo-browser") return dir
      } catch (err) {
        throw new Error(`cannot read ${file}: ${err instanceof Error ? err.message : "invalid JSON"}`)
      }
    }
    const parent = path.dirname(dir)
    if (parent === dir) return process.cwd()
    dir = parent
  }
}

async function readJson(file: string): Promise<unknown> {
  if (!(await Bun.file(file).exists())) return {}
  const text = await Bun.file(file).text()
  if (text.trim().length === 0) return {}
  try {
    return JSON.parse(text) as unknown
  } catch (err) {
    throw new Error(`cannot parse ${file}: ${err instanceof Error ? err.message : "invalid JSON"}`)
  }
}




